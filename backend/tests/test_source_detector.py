def test_detect_suricata():

    raw = """{
        "event_type": "alert",
        "src_ip": "10.0.0.5",
        "dest_ip": "8.8.8.8",
        "flow_id": 123,
        "alert": {
            "signature": "Test attack"
        }
    }"""

    result = detector.detect(raw, "json")

    assert result["source"] == "suricata"


