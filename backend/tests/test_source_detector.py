from app.services.source_detector import SourceDetector


detector = SourceDetector()


def test_detect_fortigate():

    raw = (
        'date=2026-09-19 time=18:30:00 '
        'devname="FGT-01" devid="FG123" '
        'logid="0000000013" type="traffic" '
        'subtype="forward" srcip=10.0.0.5 '
        'dstip=8.8.8.8 action="deny" '
        'policyid=10'
    )

    result = detector.detect(raw, "key_value")

    assert result["source"] == "fortigate"
    assert result["vendor"] == "Fortinet"
    assert result["confidence"] > 0.9


def test_detect_cisco_asa():

    raw = (
        "%ASA-6-302013: Built outbound TCP "
        "connection 123 for outside"
    )

    result = detector.detect(raw, "syslog")

    assert result["source"] == "cisco_asa"


